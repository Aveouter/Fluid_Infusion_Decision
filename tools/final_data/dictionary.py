def generate(package,public):
    package=Path(package);public=Path(public);public.mkdir(parents=True,exist_ok=True)
    entries=[];missing=set()
    for path in sorted(package.rglob('*.csv')):
        rel=path.relative_to(package).as_posix()
        if rel.startswith(('provenance/build_inputs/','provenance/final_builder/','dictionary/')):continue
        df=pd.read_csv(path,nrows=1000,low_memory=False)
        reference=rel.startswith(('hourly/','evidence/','fluid_lots/','fluid_segments/','provenance/','validation/'))
        for column in df:
            description=DEFINITIONS.get(column)
            if description is None:missing.add(column);continue
            numeric=column.endswith(('_ml','_ml_h','_hour')) or column in ['value','hour','hour_start','origin_hour']
            unit='mL/h' if column.endswith('_ml_h') else 'mL' if column.endswith('_ml') else 'hour_from_injury' if column.endswith('_hour') or column in ['hour','hour_start','origin_hour','available_at_hour'] else 'see_unit_or_clinical_field'
            usage='reference_or_provenance_only' if reference else 'conditional_source_requires_availability_filter'
            if rel.startswith('causal_history/'):usage='asof_predictor_state_estimate'
            if rel.startswith('cohort/'):usage='join_and_eligibility_metadata_not_model_feature'
            identifier=column.endswith('_id') or column in ['patient_id','form_id','inner_seq','source_record_numbers','source_excel_rows']
            entries.append(dict(table=rel,field=column,logical_type='identifier_string' if identifier else 'numeric' if numeric else str(df[column].dtype),unit=unit,
                description=description,source='See table lineage in METHODS.md; source IDs/record offsets retained in this table or linked ledgers',
                missing_and_zero='CSV空字段为未知/不适用；数值0仅按该字段明确规则生成，不由通用填补产生',
                permitted_use=usage))
    if missing:raise ValueError('Undocumented columns: '+', '.join(sorted(missing)))
    dictionary=package/'dictionary';dictionary.mkdir(exist_ok=True)
    frame=pd.DataFrame(entries);frame.to_csv(dictionary/'fields.csv',index=False,encoding='utf-8-sig')
    frame.to_csv(public/'fields.csv',index=False,encoding='utf-8-sig')
    observations=pd.read_csv(package/'observations/records.csv',usecols=['field','unit','qualifier','method'])
    fields=observations.drop_duplicates().sort_values(['field','unit','qualifier','method'])
    fields['aggregation']='same patient/hour/field/unit/qualifier median; urine recorded amounts sum only within matching units; residual urine separate'
    fields.to_csv(dictionary/'clinical_fields.csv',index=False,encoding='utf-8-sig')
    fields.to_csv(public/'clinical_fields.csv',index=False,encoding='utf-8-sig')
    print(json.dumps(dict(tables=frame.table.nunique(),documented_fields=len(frame),clinical_field_variants=len(fields))))


def main():
    p=argparse.ArgumentParser();p.add_argument('--package',type=Path,required=True);p.add_argument('--public',type=Path,required=True);a=p.parse_args();generate(a.package,a.public)


if __name__=='__main__':main()
